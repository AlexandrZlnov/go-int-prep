// то данная структура реализуя интерфейс будет иметь в metod set оба варианта и через указатель и через значение.
//
// 2 При передаче в функцию структуры реализующующей интерфейс (checkErr(e) при func checkErr(err error)) эта структура оборачивается интерфейсом и имеет вид:
// -- type (динамический тип) = типу переданной структуры и
// -- data (указатель на данные структуры)
//
// 3 Переменная типаа структуры объявленная через var e *errorString имеет значение nil. Но передавяю такое заначение в интерфейс, интерфейс обернет его и
// и type(динамический тип интерфейса) = *errorString. >> такой интерфейс не будет != nil
//
// 4 new возвращает указатель заданного типа на данные со значеним по умолчанию
