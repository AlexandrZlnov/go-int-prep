package main

import (
	"fmt"
)

type errorString struct {
	code int
}

func (e errorString) Error() string {
	return fmt.Sprintf("error message: %v", e.code)
}

func checkErr(err error) bool {
	return err != nil
}

func main() {
	var e *errorString // объявление без присовения значения поэтому e == nil
	if checkErr(e) {   // method set для e включает так же ресивер через указатель поэтому эсть реализация интерфейса error (*errorString реализует интерфейс error)
		fmt.Println(1, e) // в checkErr передается не nil интерфейс (так как известен тип) err != nil возвращает true, потому что интерфейс не является nil.
		// Поэтому напечатаестя: 1, nil
	}

	e = new(errorString) // new(errorString) выделяет память под структуру errorString, инициализирует ее нулевыми значениями и возвращает указатель *errorString.
	if checkErr(e) {     // будет аналогично предыдушему случаю. e это *errorString и он реализует интерфейс error. Поскольку в методе checkErr интерфейс не nil проверка даст true
		//Перед выводом значения пакет fmt проверяет, реализует ли тип специальные интерфейсы (error, fmt.Stringer и др.). Если реализует — вызывает соответствующий метод (Error(), String()), иначе печатает само значение.
		// поэтому не бутед напечатан &e, а будеи вызван метод Error и напечатается строка которую он вернет.
		fmt.Println(2, e) // 2, error message: 0
	}

	e = nil           // после прошлого шага e = *errorString{code: 0}. Текущий шаг дает e *errorString = nil. Но type интерфейса = *errorString. поэтому интерфейс не nil
	if !checkErr(e) { // e реализует интерфейс error. проверка даст !true
		fmt.Println(3, e) // ничего не напечатается
	}

	var el error       // el это nil итрерфейс. Тоесть динамический тип интерфейса = nil и value = nil
	if !checkErr(el) { // проверка дасть !false = true
		fmt.Println(4, el) // напечатается 4, <nil>
	}

	err := new(errorString) // new возвращает указатель на errorString{0}
	if checkErr(*err) {     // передаем разименованный казатель, тоесть передаем структуру errorString{0}. Она реализует интерфейс error и функция вернет true
		fmt.Println(5, err) // напечатат: 5, error message: 0
	}

	perr := new(*errorString) // new возвращает указатель на ячейку памяти где лежить указатель которому присвоено нулевое значение. Тоесть perr = **errorString равный nil.
	// или понятнее так: var p *errorString = nil где perr := &p
	if checkErr(*perr) { // передаем на проверку разименованный указатель, тоессть *errorString = nil. Но этот тип реализует интерфейс и динамический тип интерфейса = *errorString. Тоесть не nil
		// поэтому проверка вернет true
		fmt.Println(6, perr) // **errorString не реализует интерфей error, поэтому метод Error не вызовется. напечатается: 6, и адрес ячейки памяти
	}

}

